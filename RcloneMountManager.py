def get_app_version() -> str:
    """
    Determine application version dynamically:
    1. _version.py module (generated by build workflows or PyInstaller spec)
    2. version.txt file (bundled in PyInstaller _MEIPASS or local BASE_DIR)
    3. APP_VERSION or GITHUB_REF_NAME environment variable
    4. Git tag via 'git describe --tags --always' (if in a git repo)
    5. Fallback version ('1.2.0')
    """
    # 1. Generated module
    try:
        import _version
        v = getattr(_version, "__version__", None)
        if v:
            v_str = str(v).strip()
            return v_str[1:] if v_str.lower().startswith("v") else v_str
    except ImportError:
        pass

    # 2. Bundled version.txt in PyInstaller _MEIPASS or BASE_DIR
    for dir_path in [getattr(sys, "_MEIPASS", None), BASE_DIR]:
        if dir_path:
            v_file = Path(dir_path) / "version.txt"
            if v_file.exists():
                try:
                    content = v_file.read_text(encoding="utf-8").strip()
                    if content:
                        return content[1:] if content.lower().startswith("v") else content
                except Exception:
                    pass

    # 3. Environment variables (CI runner or build script)
    for env_key in ("APP_VERSION", "GITHUB_REF_NAME"):
        env_val = os.environ.get(env_key, "").strip()
        if env_val:
            if env_val.startswith("refs/tags/"):
                env_val = env_val[len("refs/tags/"):]
            return env_val[1:] if env_val.lower().startswith("v") else env_val

    # 4. Query git describe
    try:
        res = subprocess.run(
            ["git", "describe", "--tags", "--always"],
            cwd=str(BASE_DIR),
            capture_output=True,
            text=True,
            timeout=2,
            check=False,
        )
        if res.returncode == 0 and res.stdout.strip():
            git_ver = res.stdout.strip()
            return git_ver[1:] if git_ver.lower().startswith("v") else git_ver
    except Exception:
        pass

    return "1.2.0"

